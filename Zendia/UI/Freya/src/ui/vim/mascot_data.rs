/// Eye segment `[x0, y0, x1, y1, stroke_width]` on the 1024 emblem grid.
pub type EyeSpec = [f32; 5];

/// Mode letter vector outline centered at `(x, y)` in unit coordinates.
pub struct LetterSpec {
    pub polygons: &'static [&'static [[f32; 2]]],
    pub x: f32,
    pub y: f32,
    pub size: f32,
    pub lean_deg: f32,
}

/// Complete mascot drawing for one pose mode (`n`, `i`, `v`, `e`, `t`, `l`).
